const FALLBACK = [['Тепло', 'Понял, спасибо'], ['Коротко', 'Хорошо'], ['Деловой', 'Принял, отвечу позже']];

function suggest(text, extra = {}) {
  const t = String(text || '').trim();
  const out = [];
  const push = (tone, txt) => { if (txt && !out.some((o) => o.text === txt)) out.push({ tone, text: txt }); };
  (extra.first || []).forEach((r) => push(r.tone, r.text));             // ответы, подобранные по сроку/просьбе
  const cat = CATS.find((c) => c.re.test(t));
  (cat ? cat.out : FALLBACK).forEach((o) => push(o[0], o[1]));
  if (out.length < 3) FALLBACK.forEach((o) => push(o[0], o[1]));
  return out.slice(0, 3);
}
function category(text) { const c = CATS.find((c) => c.re.test(String(text || '').trim())); return c ? c.id : null; }

module.exports = { suggest, category };
